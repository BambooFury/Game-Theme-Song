import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root      = resolve(__dirname, '..');

const toastDir   = join(root, 'frontend', 'search-toast');
const welcomeDir = join(root, 'webkit', 'welcome');
const iconsDir   = join(welcomeDir, 'icons');
const outPath    = join(root, 'webkit', '_assets.generated.ts');

const welcomeCss  = readFileSync(join(welcomeDir, 'welcome.css'),  'utf8');
const welcomeHtml = readFileSync(join(welcomeDir, 'welcome.html'), 'utf8');

const ICON_NAMES = ['music', 'search', 'sparkles', 'zap', 'settings', 'x', 'play', 'library'];
const icons = Object.fromEntries(
  ICON_NAMES.map((name) => [name, readFileSync(join(iconsDir, `${name}.svg`), 'utf8').trim()]),
);

function asTsLiteral(s) {
  return '`' + s.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${') + '`';
}

const banner =
`// AUTO-GENERATED by scripts/build-assets.mjs — DO NOT EDIT BY HAND.
// Source: webkit/welcome/welcome.css, webkit/welcome/welcome.html, webkit/welcome/icons/*.svg
`;

const iconEntries = ICON_NAMES
  .map((name) => `  ${name}: ${asTsLiteral(icons[name])},`)
  .join('\n');

const body =
`export const WELCOME_CSS_TEMPLATE  = ${asTsLiteral(welcomeCss)};
export const WELCOME_HTML_TEMPLATE = ${asTsLiteral(welcomeHtml)};

export const WELCOME_ICONS = {
${iconEntries}
};
`;

writeFileSync(outPath, banner + '\n' + body, 'utf8');

const settingsDir = join(root, 'frontend', 'settings');
const toastCss   = readFileSync(join(toastDir, 'search-toast.css'), 'utf8');
const toastIcon  = readFileSync(join(toastDir, 'magnifier.svg'), 'utf8').trim();
const toastXIcon = readFileSync(join(toastDir, 'x.svg'), 'utf8').trim();
const toastOkIcon = readFileSync(join(toastDir, 'check.svg'), 'utf8').trim();
const settingsCss  = readFileSync(join(settingsDir, 'settings.css'), 'utf8');
const trashIcon    = readFileSync(join(settingsDir, 'trash.svg'), 'utf8').trim();
const libraryIcon  = readFileSync(join(settingsDir, 'library.svg'), 'utf8').trim();
const frontendOut = join(root, 'frontend', '_assets.generated.ts');
const frontendBanner =
`// AUTO-GENERATED by scripts/build-assets.mjs — DO NOT EDIT BY HAND.
// Source: frontend/search-toast/*, frontend/settings/*
`;
const frontendBody =
`export const SEARCH_TOAST_CSS   = ${asTsLiteral(toastCss)};
export const SEARCH_TOAST_ICON  = ${asTsLiteral(toastIcon)};
export const SEARCH_TOAST_X     = ${asTsLiteral(toastXIcon)};
export const SEARCH_TOAST_CHECK = ${asTsLiteral(toastOkIcon)};

export const SETTINGS_CSS = ${asTsLiteral(settingsCss)};
export const SETTINGS_ICONS = {
  trash: ${asTsLiteral(trashIcon)},
  library: ${asTsLiteral(libraryIcon)},
};
`;
writeFileSync(frontendOut, frontendBanner + '\n' + frontendBody, 'utf8');
console.log(`[build-assets] wrote ${frontendOut} (css: ${toastCss.length} chars)`);

console.log(
  `[build-assets] wrote ${outPath}`
  + ` (css: ${welcomeCss.length} chars, html: ${welcomeHtml.length} chars, icons: ${ICON_NAMES.length})`
);
